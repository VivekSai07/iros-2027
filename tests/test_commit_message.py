import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


class CommitMessageTests(unittest.TestCase):
    def check_message(self, message):
        with tempfile.TemporaryDirectory() as directory:
            message_path = Path(directory) / "message.txt"
            message_path.write_text(message, encoding="utf-8")
            return subprocess.run(
                [sys.executable, str(ROOT / "tools/check_commit_message.py"), str(message_path)],
                capture_output=True,
                text=True,
            )

    def test_accepts_plain_message_and_human_trailer(self):
        result = self.check_message(
            "docs: organize research workspace\n\nCo-authored-by: Researcher <researcher@example.org>\n"
        )
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_rejects_attribution_in_subject_or_body(self):
        for message in (
            "feat: add AI-generated analysis",
            "docs: update notes\n\nCo-authored-by: GitHub Copilot <copilot@example.org>",
            "docs: update notes\n\nGenerated by Claude",
            "chore: changes from Codex",
        ):
            with self.subTest(message=message):
                result = self.check_message(message)
                self.assertEqual(result.returncode, 1, result.stderr)
                self.assertIn("attribution", result.stderr.lower())

    def test_does_not_match_substrings_in_ordinary_words(self):
        result = self.check_message("fix: maintain training and repair metrics")
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()